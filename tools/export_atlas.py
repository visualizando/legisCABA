css=re.search(r'<style>(.*?)</style>',template,re.S).group(1)
skip={':root','*','body','button','input','select','button:active',':focus-visible','a','.wrap','.brand','.brand strong','.brand strong span','.eyebrow','h1','h2','h3','p','label','.skip','.skip:focus'}
def scoped(text):
    result=[];pos=0
    while pos<len(text):
        start=text.find('{',pos)
        if start<0:break
        selector=text[pos:start].strip();depth=1;end=start+1
        while depth:
            if text[end]=='{':depth+=1
            if text[end]=='}':depth-=1
            end+=1
        body=text[start+1:end-1]
        if selector.startswith('@media'):result.append(selector+'{'+scoped(body)+'}')
        else:
            selectors=[s.strip() for s in selector.split(',') if s.strip() not in skip]
            if selectors:
                selectors=[re.sub(r'#([\w-]+)',r'#atlas-\1',s) for s in selectors]
                result.append(','.join('#project-atlas '+s for s in selectors)+'{'+body+'}')
        pos=end
    return '\n'.join(result)
